// 312000  ->  "312,000원"
// toLocaleString("ko-KR") 이 세 자리마다 쉼표를 넣어 줍니다
function 원(숫자) {
  return 숫자.toLocaleString("ko-KR") + "원";
}

// 소진율에 따라 막대 색을 고릅니다 ("빠듯한 항목은 색으로 구분")
//   80% 이상 -> 빨강,  50% 이상 -> 주황,  그 아래 -> 초록
function 막대색(소진율) {
  if (소진율 >= 80) return "bar-fill--danger";
  if (소진율 >= 50) return "bar-fill--warn";
  return "bar-fill--safe";
}

// Date -> "2026-10-15" 모양의 글자 (날짜 입력칸에 넣을 때 필요)
// padStart(2, "0") 은 9를 09로 바꿔 주는 것입니다
function 날짜글자(d) {
  const 년 = d.getFullYear();
  const 월 = String(d.getMonth() + 1).padStart(2, "0");  // getMonth()는 0부터 시작
  const 일 = String(d.getDate()).padStart(2, "0");
  return 년 + "-" + 월 + "-" + 일;
}


/* -------------------------------------------------------------------
   2-2) 계산 함수 (4차시)
      화면과 상관없이 "숫자를 넣으면 숫자가 나오는" 함수만 따로 모았습니다.
      값이 이상하게 나오면 이 두 함수부터 의심하면 됩니다.
   ------------------------------------------------------------------- */

// 오늘부터 입금일까지 며칠 남았는지 셉니다.
//   오늘이 10월 6일, 입금일이 10월 15일이면 -> 9
//   (6·7·8·…·14일, 9일 동안 버티면 15일에 돈이 들어옴)
function 남은일수계산(입금일글자) {
  // "2026-10-15" 를 "-" 로 잘라 [2026, 10, 15] 숫자 3개로 만듭니다
  const 조각 = 입금일글자.split("-").map(Number);
  const 입금일 = new Date(조각[0], 조각[1] - 1, 조각[2]);   // 달은 0부터 시작이라 -1

  // 지금 시각에서 시·분·초를 버리고 '오늘 0시'만 남깁니다.
  // 이걸 안 하면 오후에 열었을 때 8.4일처럼 소수가 나옵니다.
  const 지금 = new Date();
  const 오늘 = new Date(지금.getFullYear(), 지금.getMonth(), 지금.getDate());

  // 날짜끼리 빼면 '밀리초(1/1000초)' 차이가 나옵니다.
  // 하루 = 1000 × 60 × 60 × 24 밀리초 로 나누면 '며칠'이 됩니다.
  const 하루 = 1000 * 60 * 60 * 24;
  return Math.round((입금일 - 오늘) / 하루);
}

// 오늘의 안전 지출 금액 = (잔액 − 고정지출) ÷ 남은 일수
// Math.floor = 소수점 아래 버림. 12,400.7원처럼 나오면 12,400원으로.
// (올림을 하면 마지막 날 몇 원이 모자랄 수 있어서 버림을 씁니다)
function 안전금액계산(잔액, 고정지출, 남은일수) {
  const 쓸수있는돈 = 잔액 - 고정지출;
  if (쓸수있는돈 <= 0) return 0;     // 고정지출을 내면 남는 돈이 없을 때
  return Math.floor(쓸수있는돈 / 남은일수);
}


/* -------------------------------------------------------------------
   3) 화면에 그리기
      document.getElementById("...") = index.html에서 그 id를 가진 자리를 찾기
      .textContent = "그 자리의 글자를 이걸로 바꿔라"
   ------------------------------------------------------------------- */

// (1) 상단 - 잔액과 D-day
function 상단그리기(잔액, 남은일수) {
  document.getElementById("balance").textContent = 원(잔액);
  // 입금일을 안 넣었거나 이미 지났으면 D-day 대신 "―"
  document.getElementById("dday").textContent =
    남은일수 > 0 ? "D-" + 남은일수 : "―";
  document.getElementById("next-income").textContent =
    임시데이터.다음입금.종류 + " " + 원(임시데이터.다음입금.금액);
}

// (2) 중앙 - 오늘의 안전 지출 금액
//   계산이 안 되는 경우(입금일이 없거나 지났을 때)에는 숫자 대신 안내를 보여 줍니다
function 안전금액그리기(잔액, 고정지출, 남은일수) {
  const 금액칸 = document.getElementById("safe-amount");
  const 안내칸 = document.getElementById("today-hint");
  const 계산식칸 = document.getElementById("today-formula");

  if (!(남은일수 > 0)) {
    금액칸.textContent = "―";
    안내칸.textContent = "다음 입금 예정일을 내일 이후 날짜로 넣어 주세요";
    계산식칸.textContent = "";
    return;
  }

  const 안전금액 = 안전금액계산(잔액, 고정지출, 남은일수);
  금액칸.textContent = 원(안전금액);

  // 잔소리 대신 사실만 알려 줍니다 (설계 원칙 1)
  안내칸.textContent = 안전금액 > 0
    ? "여기까지는 써도 괜찮아요"
    : "고정지출을 내고 나면 남는 돈이 없어요";

  // 손 검산과 비교할 수 있게 계산 과정을 그대로 보여 줍니다
  계산식칸.textContent =
    "(" + 원(잔액) + " − " + 원(고정지출) + ") ÷ " + 남은일수 + "일";
}

// (2-2) '내 돈 정보' 칸의 값을 읽어 다시 계산하고 상단·중앙을 새로 그립니다
//   칸에 글자를 칠 때마다 이 함수가 불립니다
function 다시계산() {
  // 빈칸이면 Number("")가 0이 되므로 잔액·고정지출은 0원으로 계산됩니다
  const 잔액 = Number(document.getElementById("input-balance").value);
  const 고정지출 = Number(document.getElementById("input-fixed").value);
  const 입금일글자 = document.getElementById("input-income-date").value;

  // 날짜칸이 비어 있으면 "" 이라 계산할 수 없음 -> 0일로 취급
  const 남은일수 = 입금일글자 ? 남은일수계산(입금일글자) : 0;

  상단그리기(잔액, 남은일수);
  안전금액그리기(잔액, 고정지출, 남은일수);
}

// (2-3) 처음 값 채우기 + "값이 바뀌면 다시 계산해라" 연결
function 입력연결() {
  const 잔액칸 = document.getElementById("input-balance");
  const 입금일칸 = document.getElementById("input-income-date");
  const 고정지출칸 = document.getElementById("input-fixed");

  // 처음 값 (임시데이터에서 가져옴)
  잔액칸.value = 임시데이터.잔액;
  고정지출칸.value = 임시데이터.고정지출;
  const 입금일 = new Date();
  입금일.setDate(입금일.getDate() + 임시데이터.입금까지일수);   // 오늘 + 9일
  입금일칸.value = 날짜글자(입금일);

  // "input" = 칸의 내용이 한 글자라도 바뀔 때마다
  잔액칸.addEventListener("input", 다시계산);
  입금일칸.addEventListener("input", 다시계산);
  고정지출칸.addEventListener("input", 다시계산);
}

// (3) 중단 - 카테고리 6개를 반복해서 막대로 만들기
function 카테고리그리기() {
  const 목록 = document.getElementById("category-list");
  목록.innerHTML = "";   // 다시 그릴 때를 대비해 먼저 비웁니다

  // forEach = 배열의 항목을 하나씩 꺼내 같은 일을 반복
  임시데이터.카테고리.forEach(function (항목) {
    const li = document.createElement("li");   // <li> 태그를 새로 만들고
    li.innerHTML = `
      <div class="category-head">
        <span class="category-name">${항목.이름}</span>
        <span class="category-left">남은 ${원(항목.남은금액)} · ${항목.소진율}% 사용</span>
      </div>
      <div class="bar">
        <div class="bar-fill ${막대색(항목.소진율)}" style="width:${항목.소진율}%"></div>
      </div>
    `;
    목록.appendChild(li);                       // <ul> 안에 붙입니다
  });
}

// (4) 하단 - 빠른 입력 버튼 3개
function 빠른입력그리기() {
  const 목록 = document.getElementById("quick-list");
  목록.innerHTML = "";

  임시데이터.빠른입력.forEach(function (항목) {
    const button = document.createElement("button");
    button.className = "quick-btn";
    button.innerHTML = `
      <span class="quick-btn-name">${항목.이름}</span>
      <span class="quick-btn-price">${원(항목.금액)}</span>
    `;
    // 누르면 지출 입력 화면으로 이동합니다 (3차시)
    button.addEventListener("click", function () {
      location.href = "expense.html";
    });
    목록.appendChild(button);
  });
}


